export type CoreMessageCode = keyof typeof CORE_MESSAGES;

/** The template of a code with its places filled. A place with no value keeps its braces, so a gap shows. */
export function formatMessage(template: string, params: Readonly<Record<string, string | number>> = {}): string {
  return template.replace(/\{([a-z_0-9]+)\}/g, (whole: string, name: string) => (name in params ? String(params[name]) : whole));
}

/** A message by its code: `{ code, params, text }` with the English text. */
export function coreMessage(code: CoreMessageCode, params: Readonly<Record<string, string | number>> = {}): CoreMessage {
  return { code, params, text: formatMessage(CORE_MESSAGES[code], params) };
}

